function getFrames(character: 'begeleider' | 'milan', state: string) {
  if (character === 'begeleider') {
    return [BEGELEIDER_IDLE_1, BEGELEIDER_IDLE_2];
  }
  switch (state) {
    case 'angry':
    case 'stressed':
      return [MILAN_ANGRY_1, MILAN_ANGRY_2];
    case 'calm':
    case 'happy':
      return [MILAN_CALM, MILAN_CALM];
    default:
      return [MILAN_IDLE_1, MILAN_IDLE_2];
  }
}

export function PixelAvatar({ character, state: avatarState, size = 80, className = '' }: PixelAvatarProps) {
  const [frame, setFrame] = useState(0);
  const frames = getFrames(character, avatarState);
  const palette = PALETTES[character];
  const speed = avatarState === 'angry' || avatarState === 'stressed' ? 300 : 600;

  useEffect(() => {
    const interval = setInterval(() => {
      setFrame((f) => (f + 1) % frames.length);
    }, speed);
    return () => clearInterval(interval);
  }, [frames.length, speed]);

  const grid = frames[frame];

  // Bounce animation for stressed/angry
  const bounceClass =
    avatarState === 'stressed' || avatarState === 'angry'
      ? 'animate-bounce'
      : avatarState === 'walk'
        ? 'animate-pulse'
        : '';

  return (
    <div className={`${bounceClass} ${className}`} style={{ width: size, height: size }}>
      <svg
        viewBox="0 0 16 16"
        width={size}
        height={size}
        style={{ imageRendering: 'pixelated' }}
      >
        {grid.map((row, y) =>
          row.map((cell, x) => {
            if (cell === 0) return null;
            const color = palette[cell as keyof typeof palette];
            return (
              <rect
                key={`${x}-${y}`}
                x={x}
                y={y}
                width={1.05}
                height={1.05}
                fill={color}
              />
            );
          })
        )}
      </svg>
    </div>
  );
}
