function getFrames(character: 'begeleider' | 'milan', state: AvatarState): number[][][] {
  if (character === 'begeleider') {
    switch (state) {
      case 'observing':
        return [BEG_OBSERVING, BEG_IDLE_1];
      case 'approaching':
        return [BEG_APPROACHING, BEG_APPROACHING];
      case 'backing-off':
        return [BEG_BACKOFF_1, BEG_BACKOFF_2];
      default:
        return [BEG_IDLE_1, BEG_IDLE_2];
    }
  }
  // Milan
  switch (state) {
    case 'fidgeting':
      return [MILAN_FIDGET_1, MILAN_FIDGET_2];
    case 'refusing':
      return [MILAN_REFUSING_1, MILAN_REFUSING_2];
    case 'screaming':
    case 'angry':
      return [MILAN_SCREAM_1, MILAN_SCREAM_2];
    case 'throwing':
      return [MILAN_THROW_1, MILAN_THROW_2];
    case 'calming':
      return [MILAN_CALMING_1, MILAN_CALMING_2];
    case 'calm':
    case 'happy':
      return [MILAN_CALM, MILAN_CALM];
    default:
      return [MILAN_FIDGET_1, MILAN_FIDGET_2];
  }
}

function getAnimSpeed(state: AvatarState): number {
  switch (state) {
    case 'screaming':
    case 'throwing':
    case 'angry':
      return 250;
    case 'refusing':
    case 'stressed':
      return 400;
    case 'calming':
    case 'calm':
      return 900;
    default:
      return 600;
  }
}

function getBounce(state: AvatarState): string {
  switch (state) {
    case 'screaming':
    case 'throwing':
    case 'angry':
      return 'animate-bounce';
    case 'refusing':
    case 'stressed':
      return 'animate-pulse';
    default:
      return '';
  }
}

export function PixelAvatar({ character, state: avatarState, size = 80, className = '', mirrored = false }: PixelAvatarProps) {
  const [frame, setFrame] = useState(0);
  const frames = getFrames(character, avatarState);
  const palette = PALETTES[character];
  const speed = getAnimSpeed(avatarState);

  useEffect(() => {
    const interval = setInterval(() => {
      setFrame((f) => (f + 1) % frames.length);
    }, speed);
    return () => clearInterval(interval);
  }, [frames.length, speed]);

  const grid = frames[frame];

  return (
    <div className={`${getBounce(avatarState)} ${className}`} style={{ width: size, height: size, transform: mirrored ? 'scaleX(-1)' : undefined }}>
      <svg
        viewBox="0 0 16 16"
        width={size}
        height={size}
        style={{ imageRendering: 'pixelated' }}
      >
        {grid.map((row, y) =>
          row.map((cell, x) => {
            if (cell === 0) return null;
            const color = palette[cell as keyof typeof palette];
            return (
              <rect
                key={`${x}-${y}`}
                x={x}
                y={y}
                width={1.05}
                height={1.05}
                fill={color}
              />
            );
          })
        )}
      </svg>
    </div>
  );
}
